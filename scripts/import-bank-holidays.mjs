// Builds src/domain/bankHolidays.data.ts from GOV.UK's bank holiday data.
//
//   node scripts/import-bank-holidays.mjs
//
// Source: https://www.gov.uk/bank-holidays.json, which lists England and
// Wales, Scotland and Northern Ireland separately and runs a few years ahead.
// Northern Ireland is left out: its railway is not in HSP. Rerun once a year,
// or whenever a one-off bank holiday is announced.

import { writeFileSync } from 'node:fs';

const SOURCE = 'https://www.gov.uk/bank-holidays.json';
const DIVISIONS = {
  'england-and-wales': 'ENGLAND_AND_WALES',
  scotland: 'SCOTLAND',
};

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
const data = await response.json();

const sections = [];
let first = null;
let last = null;
for (const [division, constant] of Object.entries(DIVISIONS)) {
  const events = data[division]?.events;
  if (!Array.isArray(events) || events.length === 0) {
    throw new Error(`No events for ${division} in ${SOURCE}`);
  }
  const rows = events
    .map((event) => {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(event.date) || typeof event.title !== 'string') {
        throw new Error(`Unreadable event in ${division}: ${JSON.stringify(event)}`);
      }
      first = first === null || event.date < first ? event.date : first;
      last = last === null || event.date > last ? event.date : last;
      return `  '${event.date}': ${JSON.stringify(event.title.replace(/’/g, "'"))},`;
    })
    .sort();
  sections.push(
    `/** Bank holidays in ${division === 'scotland' ? 'Scotland' : 'England and Wales'}, by date. */\n` +
      `export const ${constant}: Readonly<Record<string, string>> = {\n${rows.join('\n')}\n};`,
  );
}

const retrieved = new Date().toISOString().slice(0, 10);
const output = `// Generated by scripts/import-bank-holidays.mjs - do not edit by hand.
// Source: ${SOURCE}, retrieved ${retrieved}.

/** The span of dates this data covers. Dates outside it are unknown, not ordinary. */
export const BANK_HOLIDAYS_COVER = { from: '${first}', to: '${last}', retrieved: '${retrieved}' } as const;

${sections.join('\n\n')}
`;

writeFileSync(new URL('../src/domain/bankHolidays.data.ts', import.meta.url), output);
console.log(`Wrote bank holidays ${first} to ${last}.`);
