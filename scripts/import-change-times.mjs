// Builds src/domain/changeTimes.data.ts from the RDG timetable feed.
//
//   node scripts/import-change-times.mjs path/to/RJTTFnnn.MSN path/to/RJTTFnnn.TSI
//
// The feed is the "Timetable" static feed on the National Rail Data Portal. It
// is republished with each timetable change, and so should this file be: the
// output records which feed sequence it came from.
//
// MSN (Master Station Names) is fixed-width, one row per TIPLOC, so a station
// with several TIPLOCs appears several times. Columns used, 0-indexed:
//   0      record type, "A" for a station
//   5-34   station name
//   49-51  CRS code
//   63-64  minimum change time, minutes
// A station whose rows disagree is a failure, not something to pick between.
//
// TSI (TOC Specific Interchange) is comma-separated:
//   station CRS, arriving TOC, departing TOC, change time, comment
// and overrides the MSN figure for that pair of operators.

import { readFileSync, writeFileSync } from 'node:fs';

const [msnPath, tsiPath] = process.argv.slice(2);
if (!msnPath || !tsiPath) {
  console.error('Usage: node scripts/import-change-times.mjs <file.MSN> <file.TSI>');
  process.exit(1);
}

const msn = readFileSync(msnPath, 'latin1').split(/\r?\n/);

const sequence = msn.find((line) => line.startsWith('/!! Sequence:'))?.split(':')[1]?.trim();
const generated = msn.find((line) => line.startsWith('/!! Generated:'))?.split(':')[1]?.trim();
if (!sequence || !generated) throw new Error('MSN header has no sequence or generated date.');

const stations = new Map();
const conflicts = [];
for (const line of msn) {
  if (!line.startsWith('A ') || line.includes('FILE-SPEC')) continue;
  const name = line.slice(5, 35).trim();
  const crs = line.slice(49, 52).trim();
  const raw = line.slice(63, 65).trim();
  if (!/^[A-Z0-9]{3}$/.test(crs) || !/^\d+$/.test(raw)) {
    throw new Error(`Unreadable MSN row: ${JSON.stringify(line)}`);
  }
  const minutes = Number(raw);
  const existing = stations.get(crs);
  if (existing !== undefined && existing !== minutes) conflicts.push(`${crs} (${name})`);
  stations.set(crs, minutes);
}
if (conflicts.length > 0) {
  throw new Error(`Stations with more than one change time: ${conflicts.join(', ')}`);
}

const pairs = [];
for (const line of readFileSync(tsiPath, 'latin1').split(/\r?\n/)) {
  if (line.trim() === '') continue;
  const [crs, arriving, departing, raw] = line.split(',').map((field) => field.trim());
  if (!crs || !arriving || !departing || !raw || !/^\d+$/.test(raw)) {
    throw new Error(`Unreadable TSI row: ${JSON.stringify(line)}`);
  }
  pairs.push(`  '${crs}:${arriving}:${departing}': ${Number(raw)},`);
}

const sortedStations = [...stations.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([crs, minutes]) => `  ${crs}: ${minutes},`);

const output = `// Generated by scripts/import-change-times.mjs - do not edit by hand.
// Source: RDG timetable feed, sequence ${sequence}, generated ${generated}.

/** RDG timetable feed this data was read from. */
export const CHANGE_TIMES_SOURCE = { sequence: '${sequence}', generated: '${generated}' } as const;

/** Minimum change time in minutes, by CRS code, from the MSN file. */
export const STATION_CHANGE_MINUTES: Readonly<Record<string, number>> = {
${sortedStations.join('\n')}
};

/** Change time for a pair of operators at a station, keyed "CRS:ARRIVING:DEPARTING", from the TSI file. */
export const OPERATOR_PAIR_CHANGE_MINUTES: Readonly<Record<string, number>> = {
${pairs.join('\n')}
};
`;

writeFileSync(new URL('../src/domain/changeTimes.data.ts', import.meta.url), output);
console.log(`Wrote ${stations.size} stations and ${pairs.length} operator pairs from feed ${sequence}.`);
